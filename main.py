def get_max_strength(n: int) -> int:
    """
    Вычисляет максимально возможную силу стаи драконов из N голов.
    Ограничение: у одного дракона может быть не более 7 голов.
    """
    if n <= 0:
        return 0
    if n == 1:
        return 1
    
    # Решение методом динамического программирования (DP)
    # dp[i] хранит максимальную силу для i голов
    dp = [0] * (n + 1)
    dp[0] = 1  # Базовое значение для произведения
    
    for i in range(1, n + 1):
        max_val = 0
        # Дракон может иметь от 1 до 7 голов (но не более общего числа голов i)
        for j in range(1, min(i, 7) + 1):
            max_val = max(max_val, dp[i - j] * j)
        dp[i] = max_val
        
    return dp[n]

def main():
    print("=== Расчет максимальной силы драконьей стаи ===")
    try:
        n = int(input("Введите суммарное количество голов N (0 < N < 100): ").strip())
        if 0 < n < 100:
            result = get_max_strength(n)
            print(f"Максимально возможная сила стаи из {n} голов: {result}")
        else:
            print("Ошибка: Число голов должно быть в диапазоне от 1 до 99.")
    except ValueError:
        print("Ошибка: Пожалуйста, введите корректное целое число.")

if __name__ == "__main__":
    main()
